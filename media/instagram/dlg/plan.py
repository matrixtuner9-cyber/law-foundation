def cut(segs,total):
  out=[]
  for i,(s,e) in enumerate(segs):
    a=max(0,s-0.06) if i==0 else max((segs[i-1][1]+s)/2, s-0.12)
    b=min(e+0.18,(e+segs[i+1][0])/2) if i+1<len(segs) else min(e+0.25,total)
    out.append((round(a,3),round(b,3)))
  return out
